#!/usr/bin/env node
/**
 * Embed tenant SQL migrations into a TypeScript module so they are available
 * inside the serverless provisioning runtime (no runtime filesystem access).
 *
 * Run after editing db/tenant/*.sql: npm run db:bundle-tenant-schema
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const dir = resolve(process.cwd(), 'db/tenant');
const files = readdirSync(dir).filter((name) => name.endsWith('.sql')).sort();
const entries = files.map((name) => ({
  name,
  sql: readFileSync(resolve(dir, name), 'utf8'),
}));

const header = `// AUTO-GENERATED by scripts/bundle-tenant-schema.mjs. Do not edit manually.\n`;
const body = `export interface TenantMigrationFile {\n  name: string;\n  sql: string;\n}\n\nexport const TENANT_MIGRATIONS: TenantMigrationFile[] = ${JSON.stringify(entries, null, 2)};\n`;
writeFileSync(resolve(process.cwd(), 'src/server/tenant/schema.generated.ts'), header + body);
console.log(`Bundled ${entries.length} tenant migration files.`);
