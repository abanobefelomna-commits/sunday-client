const TABLES: Record<"ar" | "en", Record<AppMessageKey, string>> = { ar, en };

export type Translate = (
  key: AppMessageKey,
  vars?: Record<string, string | number>,
) => string;

function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    vars[name] === undefined ? match : String(vars[name]),
  );
}

export function tableFor(locale: Locale): Record<AppMessageKey, string> {
  return TABLES[locale === "ar" ? "ar" : "en"];
}

export function useI18n() {
  const { locale, direction, setLocale } = useLocale();

  return useMemo(() => {
    const table = tableFor(locale);
    const tag = localeTag(locale);

    const t: Translate = (key, vars) => interpolate(table[key] ?? key, vars);

    const number = (value?: number | null): string =>
      value === null || value === undefined || Number.isNaN(value)
        ? "—"
        : new Intl.NumberFormat(tag).format(value);

    const percent = (value?: number | null): string =>
      value === null || value === undefined || Number.isNaN(value)
        ? "—"
        : `${new Intl.NumberFormat(tag, { maximumFractionDigits: 0 }).format(value)}%`;

    return { locale, direction, setLocale, t, number, percent, tag };
  }, [locale, direction, setLocale]);
}
