import type { AiModel, ModelCategory } from './types.ts';

type ProviderId = 'openai' | 'anthropic' | 'google' | 'alibaba';

interface ModelSeed {
  id: string;
  name: string;
  providerId: ProviderId;
  providerName: string;
  category: ModelCategory;
  description: string;
  descriptionAr: string;
  input: number;
  output: number;
  cacheRead?: number;
  contextWindow: number;
  maxOutputTokens: number;
  supportsTemperature?: boolean;
  supportsReasoning?: boolean;
  supportsVision?: boolean;
  supportsFiles?: boolean;
  recommended?: boolean;
  maxCompletionTokensOnly?: boolean;
}

/**
 * Curated catalogue of the chat models exposed by the SovereignEG gateway.
 *
 * Every entry was taken from the live `GET /models` catalogue: the API model
 * id, EGP pricing, context window, output limit, and input modalities are
 * copied from the provider metadata instead of being guessed. Embedding,
 * image-generation, and retired models stay out of the picker on purpose.
 */
function defineModel(seed: ModelSeed): AiModel {
  return {
    id: seed.id,
    apiModelId: seed.id,
    name: seed.name,
    providerId: seed.providerId,
    providerName: seed.providerName,
    inferencePlatform: 'SovereignEG',
    description: seed.description,
    descriptionAr: seed.descriptionAr,
    category: seed.category,
    pricing: {
      inputPer1mEgp: seed.input,
      outputPer1mEgp: seed.output,
      ...(seed.cacheRead ? { cacheReadPer1mEgp: seed.cacheRead } : {}),
      currency: 'EGP',
    },
    status: 'live',
    capabilities: {
      supportsTemperature: seed.supportsTemperature ?? true,
      requiresMaxCompletionTokensOnly: seed.maxCompletionTokensOnly,
      supportsTools: true,
      supportsStreaming: true,
      supportsJsonSchema: true,
      supportsReasoning: seed.supportsReasoning ?? true,
      supportsVision: seed.supportsVision ?? true,
      supportsFiles: seed.supportsFiles ?? true,
      contextWindow: seed.contextWindow,
      maxOutputTokens: seed.maxOutputTokens,
    },
    isRecommended: seed.recommended,
  };
}

